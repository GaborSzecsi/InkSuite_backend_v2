def order_children(root, release):
    orders = ORDERS[release]
    for node in root.iter():
        order = orders.get(node.tag)
        if order:
            rank = {tag: index for index, tag in enumerate(order)}
            node[:] = sorted(node, key=lambda child: rank.get(child.tag, len(rank)))
